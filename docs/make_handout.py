story.append(ListFlowable([
    ListItem(P("<b>Critic rejection:</b> a 'Rejected by critic' section shows an implausible/speculative novel generation was <b>discarded</b> (no agent marks its own work).", bullet)),
    ListItem(P("<b>Human approval gate:</b> the report ends waiting for a named analyst to <b>accept / amend / reject</b> each finding — nothing is promoted into guidance automatically.", bullet)),
], bulletType="bullet"))

