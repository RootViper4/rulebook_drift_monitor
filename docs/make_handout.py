    story.append(P("7 &nbsp;Prediction layer (forecast analytics)", h1))
    story.append(P(
        "A transparent <b>drift-index overlay</b> is computed in real time from the deterministic library scan "
        "(35 typologies × 40 rules = {} relevant pairs). Today: <b>coverage {:.0%}</b>, "
        "<b>drift index {:.0f}/100</b> ({}, projected to {} in 6 review cycles at current AI-evasion "
        "pressure of {:.0%}). Most at-risk next period: {}.".format(
            fc["coverage"]["pairs"], fc["coverage"]["overall"], fc["drift_index"],
            fc["drift_band"], trend["projection"], fc["ai_pressure"]["share"],
            ", ".join("{} ({} {:.2f})".format(a["typology_id"], a["name"][:22], a["hot_score"])
                      for a in fc["at_risk"][:3]),
        ), body))
    if trend["kind"] == "measured_history":
        bt = " With a roll-one-out backtest: {}".format(
            "MAD {:.2f}, MAPE {:.1f}%, bias {:.3f} (n={})".format(
                trend["backtest"]["mad"], trend["backtest"]["mape"],
                trend["backtest"]["bias"], trend["backtest"]["n_points"])) if trend["backtest"] else ""
        story.append(P(
            "Projection source: <b>measured history</b> — fitted to {} recorded runs/checkpoints of the real "
            "drift-index series (cadence ~{}d) with a widening confidence band.{}\n".format(
                trend["history_count"], trend["cadence_days"], bt),
            body))
    else:
        story.append(P(
            "Projection source: <b>library-scan baseline</b> (<b>{}</b> recorded points so far; 3+ switch to a "
            "measured-history forecast).".format(trend["history_count"]),
            body))
    story.append(P(
        "Methodology: Drift Index = coverage deficit (65 weight) + AI-evasion pressure (20) + severity floor (10) + "
        "AI-novelty concentration (5). With 3+ recorded runs/checkpoints the projection is a damped trend fitted to the "
        "MEASURED drift series (least-squares slope combined with the measured AI-evasion rate) with a confidence band "
        "and hold-out backtest; below that it falls back to a clearly-labelled damped exponential smoothing baseline. "
        "It is a <b>decision-support model</b>, not a "
        "calibrated statistical forecast — every number is reproducible from the library scan and recorded history.",
        small,
    ))
    story.append(Spacer(1, 8))
