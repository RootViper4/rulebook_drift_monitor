styles = getSampleStyleSheet()

title = ParagraphStyle("title", parent=styles["Title"], fontSize=22, leading=26, spaceAfter=6, textColor=colors.HexColor("#1a1a2e"))
h1 = ParagraphStyle("h1", parent=styles["Heading1"], fontSize=15, leading=18, textColor=colors.HexColor("#4361ee"), spaceBefore=14, spaceAfter=6)
h2 = ParagraphStyle("h2", parent=styles["Heading2"], fontSize=12, leading=15, textColor=colors.HexColor("#1a1a2e"), spaceBefore=10, spaceAfter=4)
body = ParagraphStyle("body", parent=styles["BodyText"], fontSize=10, leading=14, spaceAfter=6, alignment=TA_LEFT)
bullet = ParagraphStyle("bullet", parent=styles["BodyText"], fontSize=10, leading=13, leftIndent=18)
small = ParagraphStyle("small", parent=styles["BodyText"], fontSize=9, leading=12, textColor=colors.HexColor("#6b7280"))
code = ParagraphStyle("code", parent=styles["Code"], fontSize=9, leading=13, backColor=colors.HexColor("#f5f6fb"), borderPadding=6)

def P(txt, s=body):
    return Paragraph(txt, s)

